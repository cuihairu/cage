fn schema(yaml: &str) -> Schema {
    serde_yaml::from_str(yaml).expect("test schema must parse")
}

fn test_schema() -> Schema {
    schema(
        r"
tables:
  Item:
    name: Item
    description: Equipment definitions.
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int32 }, required: true }
      name: { name: name, type: { kind: String }, required: true, description: Display name }
      kind: { name: kind, type: { kind: Enum, value: ItemKind } }
      rarity: { name: rarity, type: { kind: Enum, value: Rarity } }
      tags: { name: tags, type: { kind: Array, value: { kind: String } } }
      prices: { name: prices, type: { kind: Map, value: { key_type: string, value_type: { kind: Int32 } } } }
      meta: { name: meta, type: { kind: Object, value: {} } }
      weight: { name: weight, type: { kind: Float64 } }
  Drop:
    name: Drop
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int64 }, required: true }
      item: { name: item, type: { kind: Enum, value: MissingEnum } }
enums:
  ItemKind:
    name: ItemKind
    description: Weapon category
    values:
      - { name: Sword, value: 1, description: Sword weapon }
      - { name: Shield, value: 2 }
  Rarity:
    name: Rarity
    values:
      - { name: common }
      - { name: rare }
  Duplicate:
    name: Duplicate
    values:
      - { name: A, value: 1 }
      - { name: B, value: 1 }
  MissingEnum:
    name: MissingEnum
    values: []
",
    )
}

fn artifact<'a>(artifacts: &'a [(String, Vec<u8>)], suffix: &str) -> &'a str {
    let (path, content) = artifacts
        .iter()
        .find(|(p, _)| p.ends_with(suffix))
        .unwrap_or_else(|| panic!("artifact {suffix} not found"));
    assert!(
        path.ends_with(suffix),
        "expected suffix {suffix}, got {path}"
    );
    std::str::from_utf8(content).expect("fbs is utf-8")
}

#[test]
fn test_generate_artifact_paths() {
    let gen = FlatbuffersTargetGenerator::default();
    let artifacts = gen.generate(&test_schema(), Some("abc123"));
    let paths: Vec<&str> = artifacts.iter().map(|(p, _)| p.as_str()).collect();
    assert_eq!(
        paths,
        vec![
            "build/fbs/Drop.fbs",
            "build/fbs/Item.fbs",
            "build/fbs/cage_enums.fbs",
        ]
    );
    // No enums file when nothing qualifies: a schema whose only enums
    // are string-backed produces table files alone.
    let bare = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int32 }, required: true }
      r: { name: r, type: { kind: Enum, value: R } }
enums:
  R:
    name: R
    values:
      - { name: only }
",
    );
    let gen = FlatbuffersTargetGenerator::default();
    assert_eq!(gen.generate(&bare, None).len(), 1);
}

#[test]
fn test_table_header_and_structure() {
    let gen = FlatbuffersTargetGenerator::default();
    let artifacts = gen.generate(&test_schema(), Some("abc123"));
    let item = artifact(&artifacts, "Item.fbs");
    assert!(item.starts_with("// Code generated by Cage — DO NOT EDIT."));
    assert!(item.contains("// schema: abc123"));
    assert!(item.contains("// table: Item"));
    assert!(item.contains("namespace cage.generated;"));
    assert!(item.contains("// Item — primary key: id"));
    assert!(item.contains("table Item {"));
    assert!(item.ends_with("root_type Item;\n"));
    // Item.kind resolves to a shared legal enum, so the enums file is
    // included.
    assert!(item.contains("include \"cage_enums.fbs\";"), "\n{item}");
}

#[test]
fn test_field_mapping_name_order_and_attributes() {
    let gen = FlatbuffersTargetGenerator::default();
    let artifacts = gen.generate(&test_schema(), None);
    let item = artifact(&artifacts, "Item.fbs");
    // Name order with numbers-free .fbs fields; scalar types per F0.
    let id = "  id: int (key);";
    assert!(
        item.contains(id),
        "key attribute on the integer pk:\n{item}"
    );
    assert!(item.contains("  name: string (required);"));
    assert!(item.contains("  tags: [string];"));
    assert!(item.contains("  weight: double;"));
    // The map rides the vector-of-entries idiom with a wrapper table.
    assert!(item.contains("  prices: [pricesValue];"));
    assert!(item.contains("table pricesValue {"));
    assert!(item.contains("key: string;"));
    assert!(item.contains("value: int;"));
    // Free-form object degrades to JSON text with a comment.
    assert!(item.contains("  meta: string;"));
    assert!(item.contains("free-form payload"));
    // The string enum degrades with a comment; the integer one refers.
    assert!(item.contains("  rarity: string;"));
    assert!(item.contains("field degrades to string"));
    assert!(item.contains("  kind: ItemKind;"));
    // An integer pk keeps the key attribute; `required` never lands on
    // a scalar (flatc restricts it to strings and vectors).
    let drop = artifact(&artifacts, "Drop.fbs");
    assert!(drop.contains("  id: long (key);"));
}

#[test]
fn test_key_attribute_respects_flatc_type_eligibility() {
    // A single-field PK whose type is flatc-ineligible (float, bool,
    // vector) must drop the `key` attribute — emitting `(key)` there
    // would be rejected by flatc.
    let gen = FlatbuffersTargetGenerator::default();
    let float_pk = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Float64 }, required: true }
enums: {}
",
    );
    let artifacts = gen.generate(&float_pk, None);
    let t = artifact(&artifacts, "T.fbs");
    assert!(t.contains("  id: double;"), "no key on a float pk:\n{t}");
    assert!(!t.contains("(key)"), "float pk must not carry (key):\n{t}");

    let bool_pk = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Bool }, required: true }
enums: {}
",
    );
    let artifacts = gen.generate(&bool_pk, None);
    let t = artifact(&artifacts, "T.fbs");
    assert!(t.contains("  id: bool;"), "no key on a bool pk:\n{t}");
    assert!(!t.contains("(key)"), "bool pk must not carry (key):\n{t}");

    // A vector pk is not a scalar key either.
    let vec_pk = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Array, value: { kind: Int32 } }, required: true }
enums: {}
",
    );
    let artifacts = gen.generate(&vec_pk, None);
    let t = artifact(&artifacts, "T.fbs");
    assert!(!t.contains("(key)"), "vector pk must not carry (key):\n{t}");

    // A string pk keeps the key attribute.
    let str_pk = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: String }, required: true }
enums: {}
",
    );
    let artifacts = gen.generate(&str_pk, None);
    let t = artifact(&artifacts, "T.fbs");
    assert!(
        t.contains("  id: string (key, required);"),
        "string pk keeps key:\n{t}"
    );

    let enum_pk = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Enum, value: Status }
      }
enums:
  Status:
    name: Status
    values:
      - { name: Active, value: 1 }
      - { name: Inactive, value: 2 }
",
    );
    let artifacts = gen.generate(&enum_pk, None);
    let t = artifact(&artifacts, "T.fbs");
    assert!(
        t.contains("  id: Status (key);"),
        "integer-backed enum pk keeps key:\n{t}"
    );
    assert!(t.contains("include \"cage_enums.fbs\";"));
}

#[test]
fn test_enum_base_ladder_and_shared_file() {
    let gen = FlatbuffersTargetGenerator::default();
    let artifacts = gen.generate(&test_schema(), Some("h"));
    let enums = artifact(&artifacts, "cage_enums.fbs");
    assert!(enums.contains("namespace cage.generated;"));
    // 1..=2 fits ubyte — smallest legal base wins.
    assert!(enums.contains("enum ItemKind : ubyte {"), "\n{enums}");
    assert!(enums.contains("  Sword = 1,"), "\n{enums}");
    assert!(enums.contains("  Shield = 2,"));
    // Duplicate values disqualify the whole enum (flatc has no
    // allow_alias): `Duplicate` stays out of the shared file.
    assert!(!enums.contains("enum Duplicate"), "\n{enums}");
    // The referencing table includes the enums file.
    let item = artifact(&artifacts, "Item.fbs");
    assert!(item.contains("include \"cage_enums.fbs\";"));

    // Base ladder: negative values shift to signed, wide values widen.
    let wide = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int32 }, required: true }
      s: { name: s, type: { kind: Enum, value: Signed } }
      u: { name: u, type: { kind: Enum, value: Wide } }
enums:
  Signed:
    name: Signed
    values:
      - { name: Neg, value: -5 }
      - { name: Pos, value: 5 }
  Wide:
    name: Wide
    values:
      - { name: Big, value: 4294967296 }
",
    );
    let artifacts = gen.generate(&wide, None);
    let enums = artifact(&artifacts, "cage_enums.fbs");
    assert!(enums.contains("enum Signed : byte {"), "\n{enums}");
    assert!(enums.contains("enum Wide : ulong {"), "\n{enums}");
}

#[test]
fn test_nested_array_and_map_wrappers() {
    let nested = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int32 }, required: true }
      grid: { name: grid, type: { kind: Array, value: { kind: Array, value: { kind: Int32 } } } }
      index: { name: index, type: { kind: Map, value: { key_type: int, value_type: { kind: Array, value: { kind: String } } } } }
enums: {}
",
    );
    let gen = FlatbuffersTargetGenerator::default();
    let artifacts = gen.generate(&nested, None);
    let t = artifact(&artifacts, "T.fbs");
    // Array of arrays: outer vector over a wrapper table.
    assert!(t.contains("  grid: [gridValue];"), "\n{t}");
    assert!(t.contains("table gridValue {"));
    assert!(t.contains("items: [int];"));
    // Map of array: entry table over a wrapper table.
    assert!(t.contains("  index: [indexEntry];"), "\n{t}");
    assert!(t.contains("table indexEntry {"));
    assert!(t.contains("key: long;"));
    assert!(t.contains("value: indexValue;"));
    assert!(t.contains("table indexValue {"));
}

#[test]
fn test_keyword_escaping_and_determinism() {
    let kw = schema(
        r"
tables:
  Table:
    name: Table
    primary_key: [key]
    fields:
      key: { name: key, type: { kind: String }, required: true }
      double: { name: double, type: { kind: Float64 } }
enums: {}
",
    );
    let gen = FlatbuffersTargetGenerator::default();
    let artifacts = gen.generate(&kw, None);
    let t = artifact(&artifacts, "Table.fbs");
    // Keyword idents escape with a trailing underscore; the table name
    // itself collides with `table` and escapes too.
    assert!(t.contains("table Table_ {"), "\n{t}");
    assert!(t.contains("  key_: string (key, required);"), "\n{t}");
    assert!(t.contains("  double_: double;"), "\n{t}");

    // Same schema, same bytes — twice (schema hash included in both).
    let again = gen.generate(&kw, Some("h"));
    let first = gen.generate(&kw, Some("h"));
    assert_eq!(
        first.iter().map(|(p, c)| (p, c)).collect::<Vec<_>>(),
        again.iter().map(|(p, c)| (p, c)).collect::<Vec<_>>()
    );
}

#[test]
fn test_from_config_reads_both_target_options() {
    let mut options = indexmap::IndexMap::new();
    options.insert(
        "namespace".to_string(),
        serde_json::Value::String("demo.ns".to_string()),
    );
    options.insert(
        "enums_file".to_string(),
        serde_json::Value::String("defs/enums.fbs".to_string()),
    );
    let config = TargetConfig {
        format: "flatbuffers".to_string(),
        output_dir: "build/fbs".to_string(),
        file_template: Some("{table}_gen.fbs".to_string()),
        options: Some(options),
    };
    let gen = FlatbuffersTargetGenerator::from_config(&config);
    assert_eq!(gen.output_dir, PathBuf::from("build/fbs"));
    assert_eq!(gen.file_template, "{table}_gen.fbs");
    assert_eq!(gen.namespace, "demo.ns");
    assert_eq!(gen.enums_file, "defs/enums.fbs");
}

#[test]
fn test_scalar_fields_use_the_expected_fbs_types() {
    let schema = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int32 }, required: true }
      i8: { name: i8, type: { kind: Int8 } }
      i16: { name: i16, type: { kind: Int16 } }
      i64: { name: i64, type: { kind: Int64 } }
      u8: { name: u8, type: { kind: UInt8 } }
      u16: { name: u16, type: { kind: UInt16 } }
      u32: { name: u32, type: { kind: UInt32 } }
      u64: { name: u64, type: { kind: UInt64 } }
      f32: { name: f32, type: { kind: Float32 } }
      f64: { name: f64, type: { kind: Float64 } }
      bytes: { name: bytes, type: { kind: Bytes } }
enums: {}
",
    );
    let artifacts = FlatbuffersTargetGenerator::default().generate(&schema, Some("hash"));
    let t = artifact(&artifacts, "T.fbs");
    for line in [
        "  i8: byte;",
        "  i16: short;",
        "  i64: long;",
        "  u8: ubyte;",
        "  u16: ushort;",
        "  u32: uint;",
        "  u64: ulong;",
        "  f32: float;",
        "  f64: double;",
        "  bytes: [ubyte];",
        "  id: int (key);",
    ] {
        assert!(t.contains(line), "missing {line} in\n{t}");
    }
}

#[test]
fn test_freeform_fields_and_nested_maps_degrade_or_wrap_deterministically() {
    let schema = schema(
        r#"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int32 }, required: true }
      null: { name: null, type: { kind: Null } }
      any: { name: any, type: { kind: Any } }
      obj: { name: obj, type: { kind: Object, value: {} } }
      union: { name: union, type: { kind: TaggedUnion, value: { tag: "$type", branches: {} } } }
      bad_enum: { name: bad_enum, type: { kind: Enum, value: Broken } }
      nested: { name: nested, type: { kind: Map, value: { key_type: string, value_type: { kind: Map, value: { key_type: int, value_type: { kind: Bool } } } } } }
enums:
  Broken:
    name: Broken
    values:
      - { name: Text, value: not-a-number }
"#,
    );
    let artifacts = FlatbuffersTargetGenerator::default().generate(&schema, None);
    let t = artifact(&artifacts, "T.fbs");
    assert!(t.contains("  null_: string;"), "{t}");
    assert!(t.contains("  any: string;"), "{t}");
    assert!(t.contains("  obj: string;"), "{t}");
    assert!(t.contains("  union_: string;"), "{t}");
    assert!(t.contains("  bad_enum: string;"), "{t}");
    assert!(t.contains("free-form payload"), "{t}");
    assert!(t.contains("enum \"Broken\""), "{t}");
    assert!(t.contains("  nested: [nestedEntry];"), "{t}");
    assert!(t.contains("table nestedEntry {"), "{t}");
    assert!(t.contains("key: string;"), "{t}");
    assert!(t.contains("value: nestedValue;"), "{t}");
    assert!(t.contains("table nestedValue {"), "{t}");
    assert!(t.contains("key: long; value: bool;"), "{t}");
}

/// Collections nested past the first level are hosted in wrapper
/// tables: the inner `items:` / `key:` lines render into their own
/// tables, and the outer field names the wrapper.
#[test]
fn nested_collections_render_wrapper_tables() {
    let s = schema(
        r"
tables:
  T:
    name: T
    primary_key: [id]
    fields:
      id: { name: id, type: { kind: Int32 }, required: true }
      deep: { name: deep, type: { kind: Array, value: { kind: Map, value: { key_type: int, value_type: { kind: Array, value: { kind: String } } } } } }
      deepmap: { name: deepmap, type: { kind: Map, value: { key_type: int, value_type: { kind: Array, value: { kind: String } } } } }
enums: {}
",
    );
    let artifacts = FlatbuffersTargetGenerator::default().generate(&s, Some("hash"));
    let t = artifact(&artifacts, "T.fbs");
    assert!(t.contains("deepValue"), "{t}");
    assert!(t.contains("deepmapValue"), "{t}");
    assert!(t.contains("key: long;"), "{t}");
    assert!(t.contains("items: [string];"), "{t}");
}
