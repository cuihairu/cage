/// Collapse each line's whitespace (tabs + alignment padding) so tests
/// assert structure, not gofmt's byte-level column padding.
fn normalized(src: &str) -> Vec<String> {
    src.lines()
        .map(|l| l.split_whitespace().collect::<Vec<_>>().join(" "))
        .collect()
}

